/* ===== ניסוח משותף לשני הדפים ===== */

/* "משנת תשפ״ד ועד שנת תשפ״ו" · "מחזור תשפ״ו" · ריק כשאין פילוח אמין */
function yearsPhrase(s){
  const y = (s && s.years) || [];
  if(!y.length) return '';
  if(y.length === 1) return 'מחזור ' + y[0];
  return 'משנת ' + y[0] + ' ועד שנת ' + y[y.length-1];
}

